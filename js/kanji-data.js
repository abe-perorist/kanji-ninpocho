function parseExample(text) {
    const [word, reading] = text.split('=');
    const m = reading.match(/^(.*)\[(.+)\](.*)$/);
    if (!m) throw new Error(`例の書き方がおかしい: ${text}`);
    return { word, pre: m[1], yomi: m[2], post: m[3] };
}

function parseBlock(block, grade) {
    return block
        .trim()
        .split('\n')
        .map(line => {
            const [k, kun, on, ...examples] = line.trim().split('|');
            return {
                k,
                grade,
                kun: kun === '-' ? [] : kun.split(' '),
                on: on === '-' ? [] : on.split(' '),
                examples: examples.map(parseExample),
            };
        });
}

export const GRADES = [1, 2, 3];

export const KANJI = [
    ...parseBlock(GRADE1, 1),
    ...parseBlock(GRADE2, 2),
    ...parseBlock(GRADE3, 3),
];

export function kanjiByGrade(grade) {
    return KANJI.filter(x => x.grade === grade);
}

export function getKanji(k) {
    return KANJI.find(x => x.k === k);
}
